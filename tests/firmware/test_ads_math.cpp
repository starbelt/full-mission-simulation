int main() {
  const size_t n = sizeof(FRAMES) / sizeof(FRAMES[0]);
  for (size_t i = 0; i < n; i++) {
    const TestFrame *tf = &FRAMES[i];
    char tag[24];
    snprintf(tag, sizeof(tag), "seq %d", tf->seq);

    // Copy into local arrays exactly as the firmware's AdsInput holds them,
    // so any in-place mutation by adsCompute is observable (and cannot
    // fault on read-only data in the host build).
    float gyro[3] = {tf->gyro[0], tf->gyro[1], tf->gyro[2]};
    float mag[3] = {tf->mag[0], tf->mag[1], tf->mag[2]};
    float sun[3] = {tf->sun[0], tf->sun[1], tf->sun[2]};
    float refSun[3] = {tf->refSun[0], tf->refSun[1], tf->refSun[2]};
    float refMag[3] = {tf->refMag[0], tf->refMag[1], tf->refMag[2]};
    float magCopy[3] = {mag[0], mag[1], mag[2]};
    float sunCopy[3] = {sun[0], sun[1], sun[2]};
    float rsCopy[3] = {refSun[0], refSun[1], refSun[2]};
    float rmCopy[3] = {refMag[0], refMag[1], refMag[2]};

    AdsFrameResult r;
    adsCompute(gyro, mag, sun, refSun, refMag, &r);

    // 1. Root-cause check: the compute path must not mutate its inputs.
    for (int k = 0; k < 3; k++) {
      char what[48];
      snprintf(what, sizeof(what), "mag[%d] mutated", k);
      checkMsg(mag[k] == magCopy[k], tag, what);
      snprintf(what, sizeof(what), "sun[%d] mutated", k);
      checkMsg(sun[k] == sunCopy[k], tag, what);
      snprintf(what, sizeof(what), "refSun[%d] mutated", k);
      checkMsg(refSun[k] == rsCopy[k], tag, what);
      snprintf(what, sizeof(what), "refMag[%d] mutated", k);
      checkMsg(refMag[k] == rmCopy[k], tag, what);
    }

    // 2. Emitted norms are the ORIGINAL magnitudes, not post-normalization.
    checkNum(fabsf(r.mag_norm - tf->exp_mag_norm) <= 1e-4f * tf->exp_mag_norm,
             tag, "mag_norm", r.mag_norm, tf->exp_mag_norm, 1e-4f * tf->exp_mag_norm);
    checkNum(fabsf(r.sun_norm - tf->exp_sun_norm) <= 1e-4f * tf->exp_sun_norm,
             tag, "sun_norm", r.sun_norm, tf->exp_sun_norm, 1e-4f * tf->exp_sun_norm);

    // 3. Sun/MAG separation angle (firmware emits angleBetween(mag, sun)).
    checkNum(fabsf(r.angle_deg - tf->exp_angle_deg) <= 0.05f,
             tag, "angle_deg", r.angle_deg, tf->exp_angle_deg, 0.05f);

    // 4. Quaternion vs ahrs TRIAD reference, within float32 tolerance.
    checkNum(quatAngleDeg(r.q, tf->exp_q) <= 0.1f, tag, "quat_angle",
             quatAngleDeg(r.q, tf->exp_q), 0.0f, 0.1f);
  }

  // 5. Exact half-turn: a 180 deg rotation has zero scalar part, so the
  // trace branch of dcmToQuaternion divides by ~0 / takes signf(0) == 0 and
  // used to emit the all-zero quaternion with valid=1. Reference Sun/MAG
  // (0,0,1) and (0,1,0) with a body frame rotated 180 deg about +Z.
  {
    const char *tag = "half turn";
    float A[3][3] = {{-1, 0, 0}, {0, -1, 0}, {0, 0, 1}};
    float q[4] = {0, 0, 0, 0};
    dcmToQuaternion(A, q);
    float qnorm = sqrtf(q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]);
    checkNum(fabsf(qnorm - 1.0f) <= 1e-4f, tag, "quat norm", qnorm, 1.0f, 1e-4f);
    float expected[4] = {0, 0, 0, 1};
    checkNum(quatAngleDeg(q, expected) <= 0.1f, tag, "quat_angle",
             quatAngleDeg(q, expected), 0.0f, 0.1f);

    // Same half-turn through the full per-frame compute path: Sun/MAG
    // vectors must stay non-parallel after the rotation.
    float gyro[3] = {0, 0, 0};
    float mag[3] = {0, -1, 0};
    float sun[3] = {0, 0, 1};
    float refSun[3] = {0, 0, 1};
    float refMag[3] = {0, 1, 0};
    AdsFrameResult r;
    adsCompute(gyro, mag, sun, refSun, refMag, &r);
    checkMsg(r.valid == 1, tag, "valid");
    qnorm = sqrtf(r.q[0] * r.q[0] + r.q[1] * r.q[1] + r.q[2] * r.q[2] + r.q[3] * r.q[3]);
    checkNum(fabsf(qnorm - 1.0f) <= 1e-4f, tag, "computed quat norm", qnorm, 1.0f, 1e-4f);
    checkNum(quatAngleDeg(r.q, expected) <= 0.1f, tag, "computed quat_angle",
             quatAngleDeg(r.q, expected), 0.0f, 0.1f);
  }

  if (failures == 0) {
    printf("OK: %zu frames passed\n", n);
    return 0;
  }
  printf("%d failures\n", failures);
  return 1;
}
