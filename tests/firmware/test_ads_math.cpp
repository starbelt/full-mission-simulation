// Host-compiled regression test for the PocketADCS ADS firmware compute path.
//
// Includes esp32/src/ads_math.h -- the exact code the firmware compiles --
// and exercises serialized S frames (including seq >= 1) exactly as the
// ESP32-S3 HIL firmware parses them.
//
// Regression target: the original triadDcm() normalized its four input
// vectors in place, so adsTask() then emitted mag_norm = vecNorm(mag) == 1.0
// instead of the original ~1e-5 T magnetometer magnitude on every frame
// (confirmed in captured HIL replies: mag_norm 1.000000e+00 on all 39 frames).
//
// Expected norm/angle/quaternion values were computed with the reference
// implementation (ahrs TRIAD + chiaverini, float64) on the same float32
// frame values the firmware receives; tolerances below cover float32 and
// serialization round-off.
//
// Build with a host compiler, e.g.:
//   g++ -std=c++11 -O2 -I esp32/src tests/firmware/test_ads_math.cpp -o test_ads_math
//
// Generated by scratch/gen_ads_test.py from examples/hil_stream.py frames
// (20 s @ 2 Hz truth run); do not edit the table by hand.

#include "ads_math.h"

#include <cmath>
#include <cstdio>

static int failures = 0;

static void checkNum(bool ok, const char *tag, const char *what, float got, float exp, float tol) {
  if (!ok) {
    failures++;
    printf("FAIL %s %s: got %.9g expected %.9g (tol %.9g)\n", tag, what, got, exp, tol);
  }
}

static void checkMsg(bool ok, const char *tag, const char *what) {
  if (!ok) {
    failures++;
    printf("FAIL %s %s\n", tag, what);
  }
}

// Quaternion separation in degrees, sign-insensitive (q and -q are the same
// rotation), matching examples/hil_stream.py. This is the ACTUAL rotation
// angle 2*acos(|q1.q2|), not the half-angle acos(|q1.q2|).
static float quatAngleDeg(const float a[4], const float b[4]) {
  double d = 0.0;
  for (int i = 0; i < 4; i++) d += (double)a[i] * (double)b[i];
  d = d < 0.0 ? -d : d;
  if (d > 1.0) d = 1.0;
  return (float)(2.0 * acos(d) * 57.295779513082325);
}

