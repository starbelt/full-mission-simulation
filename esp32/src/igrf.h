// Mean obliquity of the ecliptic, IAU 2006, radians.
inline double meanObliquity(double tt_jd) {
  const double t = (tt_jd - kJ2000Jd) / kDaysPerJulianCentury;
  const double t2 = t * t, t3 = t2 * t;
  return (84381.406 + (-46.836769 + (-0.0001831 + (0.00200340 * t) * t) * t) * t
          + 0.000000576 * t3 - 4.34e-10 * t3 * t3) * kAs2R;
}

// IAU 2006 precession, angle zeta (Lieske et al. ), radians.
inline double precessionZeta(double tt_jd) {
  const double t = (tt_jd - kJ2000Jd) / kDaysPerJulianCentury;
  const double t2 = t * t, t3 = t2 * t, t4 = t3 * t;
  return ((2306.2181 + (0.30188 + (0.017998 + (-0.0000004) * t) * t) * t) * t
          + (0.018028 * t3) - (0.0000059 * t4)) * kAs2R;
}

inline double precessionZ(double tt_jd) {
  const double t = (tt_jd - kJ2000Jd) / kDaysPerJulianCentury;
  const double t2 = t * t, t3 = t2 * t, t4 = t3 * t;
  return ((2306.2181 + (1.09468 + (0.018203 + (-0.000003) * t) * t) * t) * t
          - (0.018028 * t3) + (0.0000059 * t4)) * kAs2R;
}

inline double precessionTheta(double tt_jd) {
  const double t = (tt_jd - kJ2000Jd) / kDaysPerJulianCentury;
  const double t2 = t * t, t3 = t2 * t, t4 = t3 * t;
  return ((2004.3109 + (-0.42665 + (-0.041833 + (-0.000012) * t) * t) * t) * t
          - (0.000126 * t3) - (0.0000007 * t4)) * kAs2R;
}

// --- 3x3 matrices, row-major, applied as m * v -------------------------
//
// NOTE the sign convention of the y rotation. The IAU 2006 precession matrix
// is  P = Rz(-z) * Ry(theta) * Rz(-zeta)  with Ry PASSIVE, i.e.
//
//     Ry(a) = [[ cos a, 0, -sin a],
//              [     0, 1,      0],
//              [ sin a, 0,  cos a]]
//
// Using the active Ry instead flips the sign of the obliquity term and puts
// the whole matrix 23.4 deg -- one obliquity -- away from erfa's. That is a
// silent, plausible-looking bug; the value below is the passive form, and
// tests/test_igrf_host.py is what pins it.

inline void mat3MulVec(const double m[9], const double v[3], double out[3]) {
  out[0] = m[0] * v[0] + m[1] * v[1] + m[2] * v[2];
  out[1] = m[3] * v[0] + m[4] * v[1] + m[5] * v[2];
  out[2] = m[6] * v[0] + m[7] * v[1] + m[8] * v[2];
}

inline void mat3Mul(const double a[9], const double b[9], double out[9]) {
  for (int i = 0; i < 3; ++i) {
    for (int j = 0; j < 3; ++j) {
      out[3 * i + j] = a[3 * i + 0] * b[j] + a[3 * i + 1] * b[3 + j] +
                       a[3 * i + 2] * b[6 + j];
    }
  }
}

inline void mat3Transpose(const double a[9], double out[9]) {
  out[0] = a[0]; out[1] = a[3]; out[2] = a[6];
  out[3] = a[1]; out[4] = a[4]; out[5] = a[7];
  out[6] = a[2]; out[7] = a[5]; out[8] = a[8];
}

// ACTIVE rotation by +angle about z, matching erfa's Rz(GAST) as used in the
// verified chain: [[cos, sin, 0], [-sin, cos, 0], [0, 0, 1]].
inline void mat3RotZ(double angle, double out[9]) {
  const double c = cos(angle), s = sin(angle);
  out[0] = c;  out[1] = s;  out[2] = 0.0;
  out[3] = -s; out[4] = c;  out[5] = 0.0;
  out[6] = 0.0; out[7] = 0.0; out[8] = 1.0;
}

// PASSIVE rotation by +angle about y (see the note above mat3MulVec).
inline void mat3RotY(double angle, double out[9]) {
  const double c = cos(angle), s = sin(angle);
  out[0] = c;   out[1] = 0.0; out[2] = -s;
  out[3] = 0.0; out[4] = 1.0; out[5] = 0.0;
  out[6] = s;   out[7] = 0.0; out[8] = c;
}

inline void mat3RotX(double angle, double out[9]) {
  const double c = cos(angle), s = sin(angle);
  out[0] = 1.0; out[1] = 0.0; out[2] = 0.0;
  out[3] = 0.0; out[4] = c;   out[5] = -s;
  out[6] = 0.0; out[7] = s;   out[8] = c;
}

// Nutation in obliquity and longitude from the baked 44-term series.
// This is IAU 2000B truncated; against erfa's full series the truncation is
// worth ~10 arcsec (0.003 deg) of the total frame error.
inline void nutation(double tt_jd, double *dpsi, double *deps) {
  const double t = (tt_jd - kJ2000Jd) / kDaysPerJulianCentury;
  const double l  = 485868.249036 + 1717915923.2178 * t;
  const double lp = 1287104.79305 + 129596581.0481 * t;
  const double f  = 335779.526232 + 1739527262.8478 * t;
  const double dd = 1072260.70369 + 1602961601.2090 * t;
  const double om = 450160.398036 - 6962890.5431 * t;
  double sp = 0.0, cp = 0.0;
  for (int i = 0; i < kNutTerms; ++i) {
    const NutTerm &k = kNut[i];
    const double arg =
        (k.l * l + k.lp * lp + k.f * f + k.d * dd + k.om * om) * kAs2R;
    sp += k.dpsi * sin(arg);
    cp += k.deps * cos(arg);
  }
  *dpsi = sp;
  *deps = cp;
}

// Greenwich mean sidereal time, IAU 1982 series, radians.
//
// GAST is referenced to the TRUE EQUINOX, so it is built from GMST, not from
// the Earth rotation angle. ERA is referenced to the CIO and drifts away from
// the equinox at ~46 arcsec/year, which is 0.32 deg of frame error by 2025 --
// two orders of magnitude past the budget. jd is the UT1 Julian date; we pass
// UTC because there is no IERS table on board, which costs up to 0.9 s of
// rotation (~9 arcsec, 0.0025 deg).
inline double gmst(double jd) {
  const double d = jd - kJ2000Jd;
  const double t = d / kDaysPerJulianCentury;
  double deg = 280.46061837 + 360.98564736629 * d +
               0.000387933 * t * t - (t * t * t) / 38710000.0;
  deg = fmod(deg, 360.0);
  if (deg < 0.0) deg += 360.0;
  return deg * kDegToRad;
}

// Greenwich apparent sidereal time = GMST + equation of the equinoxes,
// the latter from the same nutation series used for P.
inline double gastFrom(double jd_ut1, double tt_jd, double dpsi, double deps) {
  const double eps = meanObliquity(tt_jd);
  const double eqeq = dpsi * cos(eps + deps) + deps;
  double g = gmst(jd_ut1) + eqeq;
  g = fmod(g, 2.0 * kPi);
  if (g < 0.0) g += 2.0 * kPi;
  return g;
}

// Precession-nutation matrix P: true equinox of date -> GCRS.
//
// P = Rz(-z) Ry(theta) Ry(-zeta), the IAU 2006 (Lieske) precession, and
// N = Rx(-eps) Rz(-dpsi) Rx(eps), the nutation rotation. Their product
// matches erfa's pnm06a to ~10 arcsec, the residual being the nutation-series
// truncation above.
inline void precessionNutationMatrix(double tt_jd, double out[9]) {
  double dpsi, deps;
  nutation(tt_jd, &dpsi, &deps);
  const double zeta = precessionZeta(tt_jd);
  const double z = precessionZ(tt_jd);
  const double theta = precessionTheta(tt_jd);
  const double eps = meanObliquity(tt_jd);

  // P = Rz(-z) * Ry(theta) * Rz(-zeta)   [Ry passive]
  double rz1[9], ry[9], rz2[9], p[9], tmp[9];
  mat3RotZ(-z, rz1);
  mat3RotY(theta, ry);
  mat3RotZ(-zeta, rz2);
  mat3Mul(rz1, ry, tmp);
  mat3Mul(tmp, rz2, p);

  // N = Rx(-eps) * Rz(-dpsi) * Rx(eps)
  double rx1[9], rz3[9], rx2[9], n[9], tmp2[9];
  mat3RotX(-eps, rx1);
  mat3RotZ(-dpsi, rz3);
  mat3RotX(eps, rx2);
  mat3Mul(rx1, rz3, tmp2);
  mat3Mul(tmp2, rx2, n);

  mat3Mul(p, n, out);
}

