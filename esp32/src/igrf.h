// Unix milliseconds -> decimal year (UTC-based; the sub-minute difference
// between UTC and TT is irrelevant at the 1e-7 deg level we care about, and
// the host likewise interpolates IGRF coefficients on UTC-derived datetimes).
inline double pocketadcsIgrfDecimalYear(int64_t epoch_ms) {
  // Calendar-exact decimal year.
  //
  // The obvious form, 2000.0 + (jd - 2451545.0) / 365.25, is only exact at
  // J2000. 365.25 is a MEAN year, so the result drifts against real calendar
  // years by up to half a day either side of a leap year. Half a day of
  // coefficient error is worth ~0.1 deg of field direction -- enough to fail
  // the accuracy budget while looking like scattered noise.
  //
  // Instead: take the calendar year of the instant, then add the fraction of
  // that year already elapsed, dividing by the true length (365 or 366).
  const double unix_s = static_cast<double>(epoch_ms) / 1000.0;
  const double days = floor(unix_s / 86400.0);
  double secs_into_day = unix_s - days * 86400.0;

  // civil_from_days (Hinnant): days since 1970-01-01 -> (y, m, d).
  //
  // Every division in Hinnant's version is INTEGER division. Doing them in
  // double without a floor silently breaks the two month tests below: `mp`
  // comes out fractional (2.2 instead of 2), so `m` is 2.2, `m <= 2.0` is
  // false, and the year correction is skipped -- which reports early-January
  // and February dates one year early.
  double z = days + 719468.0;
  const double era = floor(z / 146097.0);
  const double doe = z - era * 146097.0;                 // [0, 146096]
  const double yoe = floor((doe - floor(doe / 1460.0)
                          + floor(doe / 36524.0)
                          - floor(doe / 146096.0)) / 365.0);  // [0, 399]
  double y = yoe + era * 400.0;
  const double doy = doe - (365.0 * yoe + floor(yoe / 4.0) - floor(yoe / 100.0));
  const double mp = floor((5.0 * doy + 2.0) / 153.0);     // [0, 11], integral
  const double d = doy - floor((153.0 * mp + 2.0) / 5.0) + 1.0;
  const double m = mp + (mp < 10.0 ? 3.0 : -9.0);
  y += (m <= 2.0) ? 1.0 : 0.0;

  // Hinnant's `d` is a day-of-month, not a day-of-year. Recompute the day of
  // year directly from the civil date, which is unambiguous and avoids
  // depending on that distinction: count the days from Jan 1 of `y`.
  const int yi = static_cast<int>(y);
  const bool leap = ((yi % 4 == 0 && yi % 100 != 0) || yi % 400 == 0);
  static const int cum[12] = {0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334};
  const int mi = static_cast<int>(m);
  const int di = static_cast<int>(d);
  const int doy_i = cum[mi - 1] + di - 1 + ((mi > 2 && leap) ? 1 : 0);
  const double year_len = leap ? 366.0 : 365.0;
  const double doy_frac = (doy_i + secs_into_day / 86400.0) / year_len;
  return y + doy_frac;
}

