// IGRF-14 geomagnetic field model -- freestanding C++, no dependencies.
//
// Computes the unit GCRS magnetic-field direction at a GCRS position, on the
// ESP32-S3, so the ADS is not dependent on the host doing the physics for it.
//
// The field itself is IGRF-14 degree 13, exactly as the host's ppigrf
// evaluates it, and it is evaluated in ITRS: the host builds an ITRS
// Cartesian field vector and only THEN rotates it to GCRS, so we mirror that
// order (evaluate in ITRS, rotate out) rather than rotating the coefficients.
//
// THE FRAME CHAIN
// --------------
// The host's rotation is astropy's ITRS->GCRS applied to a *vector* (see
// _itrs_vectors_to_gcrs in src/pocketadcs_sim/truth_environment.py). Probing
// it with an orthonormal basis of field vectors, and matching it against
// erfa, gives exactly one matrix, and it holds in ROW form:
//
//     row:     v_gcrs = v_itrs @ (Rz(GAST) @ P)
//     column:  v_gcrs = (Rz(GAST) @ P).T @ v_itrs
//
// with P = pnm06a(TT) and GAST = gst06a(UT1, TT). Written for column vectors
// that is
//
//     v_gcrs = P^T @ Rz(-GAST) @ v_itrs
//
// and the inverse, used for the position, is
//
//     p_itrs = Rz(GAST) @ P @ p_gcrs
//
// THE ORDER IS LOAD-BEARING. The previous version of this file applied
// Rz(+GAST) @ P to the field, which is the TRANSPOSE of the above. A rotation
// and its transpose differ by twice the rotation angle, so that single sign
// error produced the 116-175 deg self-check failure that previously made this
// chain look broken. It was never broken; it was applied transposed.
//
// TWO MORE THINGS THAT ARE NOT OPTIONAL
// ------------------------------------
//   * Sidereal time must be GAST, and GAST is NOT the Earth rotation angle.
//     ERA is referenced to the CIO, GAST to the true equinox, and the two
//     drift apart at ~46 arcsec/year: 0.3 deg of frame error by 2025, 0.46 deg
//     by 2035. We use the IAU 1982 GMST series (which IS equinox-referenced)
//     plus the equation of the equinoxes. Substituting ERA is a 0.05 deg error
//     at 2020, growing with time.
//   * Nutation and precession are both required. Precession alone costs
//     0.37 deg; with no precession-nutation at all, worse.
//   * Polar motion is excluded (identity), per the same note as before: the
//     IGRF series is defined on the true equator and equinox.
//
// RESIDUAL ERROR SOURCES, STATED PLAINLY
// --------------------------------------
//   * UT1-UTC is not modelled (no IERS table on board), so GMST is evaluated
//     at UTC. That is worth up to ~0.9 s of rotation, i.e. ~9 arcsec =
//     0.0025 deg, and it is the largest single term left in the frame chain.
//   * The 44-term nutation series truncates IAU 2000B at ~10 arcsec
//     (0.003 deg) versus erfa's full series.
//   * Beyond 2025.0 the IGRF-14 coefficients do not exist and are
//     extrapolated. See igrfCoefficients().
//
// Coefficients here were generated numerically from erfa and from ppigrf's
// IGRF14.shc by scripts kept in tests/. They are not hand-transcribed.
//
// Measured against the host (tests/test_igrf_host.py):
//   field-direction error < 0.01 deg over 240 (position, epoch) pairs on a
//   550 km LEO orbit, 2015-2025 (the span over which IGRF-14 is defined).
//
// Freestanding rules obeyed here: <math.h>/<stdint.h> only, no M_PI, no
// exceptions, no dynamic allocation, no libc beyond the above.

