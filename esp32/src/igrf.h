// Linear interpolation of the Gauss coefficients at a decimal year. ppigrf
// interpolates linearly in time between the 5-year model epochs, so we match
// that rather than doing anything cleverer.
//
// ANCHORING AND EXTRAPOLATION, stated plainly:
//   * IGRF-14 is only PUBLISHED through 2025.0. The 2020 and 2025 columns are
//     real measurements/model values and are what the 2015-2025 validation
//     window exercises.
//   * The 2030 column is the IGRF-14 "secular variation" prediction, not a
//     measurement, and the IGRF-14 note is explicit that it is NOT the linear
//     extrapolation of 2020->2025 (the residual reaches ~24 nT in h). So it
//     must not be reproduced by extrapolating from 2020->2025.
//   * Beyond 2030.0 we therefore hold the 2025->2030 slope. That is the
//     defensible choice, and it is an EXTRAPOLATION: any accuracy claim for
//     epochs past 2025 is inherited from the predicted 2030 column, not
//     independently validated. Past 2030 it is a linear extrapolation of a
//     prediction, and grows without bound.
inline void igrfCoefficients(double year, double *g, double *h) {{
  // Locate the bracketing published epochs and interpolate linearly between
  // them, exactly as ppigrf does. `hi` is the first epoch strictly greater
  // than `year`; `lo` is the one before it. Below the first epoch the first
  // column is held; above the last, the final two columns are extrapolated.
  //
  // The search must be strict: with `kIgrfEpoch[hi] <= year`, an epoch year
  // itself lands one slot too high, and the field at a published epoch comes
  // out as a blend of that epoch and the next one.
  int hi = 0;
  while (hi < G_EPOCHS && kIgrfEpoch[hi] <= year) ++hi;
  if (hi >= G_EPOCHS) hi = G_EPOCHS - 1;   // past the last epoch: extrapolate
  int lo = hi - 1;
  if (lo < 0) {
    lo = 0;
    hi = 0;                               // before the first: hold it
  }
  double f1;
  const double span = kIgrfEpoch[hi] - kIgrfEpoch[lo];
  f1 = span > 0.0 ? (year - kIgrfEpoch[lo]) / span : 0.0;
  const double f0 = 1.0 - f1;

  // kIgrfG/kIgrfH are laid out TERM-major: the epochs of one (n,m) are
  // adjacent, so term i starts at G_EPOCHS*i and its epochs are at +0, +1.
  // Indexing them as 104*i (epoch-major) reads the wrong numbers entirely and
  // silently yields a field with the right shape and the wrong magnitude.
  for (int i = 0; i < kIgrfTerms; ++i) {
    const int b = G_EPOCHS * i;
    g[i] = f0 * kIgrfG[b + lo] + f1 * kIgrfG[b + hi];
    h[i] = f0 * kIgrfH[b + lo] + f1 * kIgrfH[b + hi];
  }
}
}

// Schmidt semi-normalised associated Legendre functions and their theta
// derivatives, by the same recursion ppigrf uses, for a single colatitude.
// Double precision throughout: the recursion is a chain of ~13 steps and the
// cancellation in dP near the equator is mild, but the field direction is the
// thing the ADS trusts, so we do not buy the ~2x speed of float here.
inline void legendreSchmidt(double theta_rad, double *P, double *dP) {
  const int nmax = kIgrfNmax;
  const double cos_theta = cos(theta_rad);
  const double sin_theta = sin(theta_rad);

  // Unnormalised recursions first, normalisation folded in per degree/order.
  double Praw[14][14], draw[14][14], S[14][14];
  for (int n = 0; n <= nmax; ++n) {
    for (int m = 0; m <= n; ++m) {
      Praw[n][m] = 0.0;
      draw[n][m] = 0.0;
      S[n][m] = 0.0;
    }
  }
  Praw[0][0] = 1.0;
  S[0][0] = 1.0;
  draw[0][0] = 0.0;

  for (int n = 1; n <= nmax; ++n) {
    for (int m = 0; m <= n; ++m) {
      if (m == n) {
        Praw[n][m] = sin_theta * Praw[n - 1][m - 1];
        draw[n][m] = sin_theta * draw[n - 1][m - 1] + cos_theta * Praw[n - 1][n - 1];
      } else if (n == 1) {
        Praw[n][m] = cos_theta * Praw[n - 1][m];
        draw[n][m] = cos_theta * draw[n - 1][m] - sin_theta * Praw[n - 1][m];
      } else {
        const double nn = static_cast<double>(n);
        const double mm = static_cast<double>(m);
        const double Knm = ((nn - 1.0) * (nn - 1.0) - mm * mm) /
                          ((2.0 * nn - 1.0) * (2.0 * nn - 3.0));
        Praw[n][m] = cos_theta * Praw[n - 1][m] - Knm * Praw[n - 2][m];
        draw[n][m] = cos_theta * draw[n - 1][m] - sin_theta * Praw[n - 1][m] -
                     Knm * draw[n - 2][m];
      }
      if (m == 0) {
        S[n][m] = S[n - 1][m] * (2.0 * n - 1.0) / n;
      } else {
        const double nn = static_cast<double>(n);
        const double mm = static_cast<double>(m);
        S[n][m] = S[n][m - 1] *
                  sqrt((nn - mm + 1.0) * (mm == 1.0 ? 2.0 : 1.0) / (nn + mm));
      }
    }
  }

  int k = 0;
  for (int n = 1; n <= nmax; ++n) {
    for (int m = 0; m <= n; ++m) {
      P[k] = Praw[n][m] * S[n][m];
      dP[k] = draw[n][m] * S[n][m];
      ++k;
    }
  }
}

// Field in ITRS, tesla, at geocentric spherical (radius_km, colatitude_deg,
// longitude_deg). Mirrors the host's _igrf14_itrs exactly, including the
// south/east -> cartesian convention.
inline void igrfFieldItrs(double radius_km, double colatitude_deg,
                          double longitude_deg, double year,
                          double b_itrs_t[3]) {
  const double theta = colatitude_deg * kDegToRad;
  const double phi = longitude_deg * kDegToRad;

  double g[kIgrfTerms], h[kIgrfTerms];
  igrfCoefficients(year, g, h);
  double P[kIgrfTerms], dP[kIgrfTerms];
  legendreSchmidt(theta, P, dP);

  const double a_over_r = kIgrfReKm / radius_km;
  const double st = sin(theta);
  double br = 0.0, bt = 0.0, bp = 0.0;
  int k = 0;
  for (int n = 1; n <= kIgrfNmax; ++n) {
    for (int m = 0; m <= n; ++m, ++k) {
      const double cosmm = cos(m * phi);
      const double sinmm = sin(m * phi);
      const double p = P[k], dp = dP[k];
      const double scale = pow(a_over_r, n + 2);
      // radial
      br += (n + 1) * scale * p * (g[k] * cosmm + h[k] * sinmm);
      // theta (host's "south" component; note the leading minus, as in ppigrf)
      bt += -scale * dp * (g[k] * cosmm + h[k] * sinmm);
      // phi (host's "east" component).
      // The P[k] factor is required: ppigrf builds this term as
      //   -m * scale * P * (g*sin(m phi) - h*cos(m phi))
      // via np.hstack((-P*sinmphi, P*cosmphi)). Omitting it leaves the
      // azimuthal field independent of colatitude.
      if (m != 0) {
        bp += -scale * m * p / st * (h[k] * cosmm - g[k] * sinmm);
      }
    }
  }

  // same south/east -> cartesian transform the host uses, in nT
  const double ct = cos(theta);
  const double sp = sin(phi), cp = cos(phi);
  b_itrs_t[0] = (br * st * cp + bt * ct * cp + bp * (-sp)) * 1.0e-9;
  b_itrs_t[1] = (br * st * sp + bt * ct * sp + bp * (cp)) * 1.0e-9;
  b_itrs_t[2] = (br * ct + bt * (-st)) * 1.0e-9;
}

