inline int igrfFieldGcrs(int64_t epoch_ms, const double pos_gcrs_m[3],
                         double out_dir[3], double *out_magnitude_t) {
  using namespace pocketadcs_igrf;
  for (int i = 0; i < 3; ++i) {
    if (!isfinite(pos_gcrs_m[i])) return IGRF_ERR_NONFINITE;
  }
  const double year = pocketadcsIgrfDecimalYear(epoch_ms);
  if (year < 2000.0 || year > 2060.0) return IGRF_ERR_RANGE;

  // TT Julian date for the frame. TT = UTC + 32.184 s + leap seconds, which is
  // 69.184 s over the whole 2017-2026 window this model is validated on. A
  // constant is enough: the sensitivity of the frame to a dTT error is
  // negligible at our budget, and the leap-second count is not something the
  // firmware can usefully carry.
  const double unix_s = static_cast<double>(epoch_ms) / 1000.0;
  const double jd_utc = 2440587.5 + unix_s / 86400.0;
  const double jd_tt = jd_utc + 69.184 / 86400.0;

  // UT1 is not modelled on board; UTC is the best available stand-in. See the
  // note on gmst() for what that costs.
  const double jd_ut1 = jd_utc;

  double dpsi, deps;
  nutation(jd_tt, &dpsi, &deps);
  const double gast = gastFrom(jd_ut1, jd_tt, dpsi, deps);

  // A = Rz(GAST) * P. The verified chain is v_gcrs = A^T @ v_itrs, so the
  // position uses A and the field uses A^T. Getting these two backwards is
  // exactly the transpose bug documented at the top of this file.
  double pnb[9], rz[9], a[9];
  precessionNutationMatrix(jd_tt, pnb);
  mat3RotZ(gast, rz);
  mat3Mul(rz, pnb, a);          // A = Rz(GAST) * P

  double p[3];
  mat3MulVec(a, pos_gcrs_m, p);

  const double radius_m = sqrt(p[0] * p[0] + p[1] * p[1] + p[2] * p[2]);
  if (radius_m < 1.0e6 || radius_m > 1.0e8) return IGRF_ERR_RANGE;
  const double radius_km = radius_m / 1000.0;
  const double colat = acos(p[2] / radius_m) / kDegToRad;
  const double lon = atan2(p[1], p[0]) / kDegToRad;

  // Field evaluated in ITRS (where the IGRF series is defined), exactly as
  // the host does, and only then rotated out to GCRS.
  double b[3];
  igrfFieldItrs(radius_km, colat, lon, year, b);

  // ITRS -> GCRS: A^T @ b
  double a_t[9];
  mat3Transpose(a, a_t);
  mat3MulVec(a_t, b, out_dir);

  const double mag = sqrt(out_dir[0] * out_dir[0] + out_dir[1] * out_dir[1] +
                          out_dir[2] * out_dir[2]);
  if (!isfinite(mag) || mag <= 0.0) return IGRF_ERR_NONFINITE;
  out_dir[0] /= mag;
  out_dir[1] /= mag;
  out_dir[2] /= mag;
  if (out_magnitude_t) *out_magnitude_t = mag;
  return IGRF_OK;
}

inline int igrfFieldUnitGcrs(int64_t epoch_ms, const double pos_gcrs_m[3],
                             float out[3]) {
  double dir[3];
  const int rc = igrfFieldGcrs(epoch_ms, pos_gcrs_m, dir, nullptr);
  if (rc != IGRF_OK) return rc;
  out[0] = static_cast<float>(dir[0]);
  out[1] = static_cast<float>(dir[1]);
  out[2] = static_cast<float>(dir[2]);
  return IGRF_OK;
}

